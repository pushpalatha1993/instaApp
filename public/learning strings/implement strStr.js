function strStr(haystack, needle) {
    return haystack.indexOf(needle);
  }
  
  
  console.log("Result:", strStr("hello", "ll"));     
  console.log("Result:", strStr("hello", "lo"));     
  console.log("Result:", strStr("aaaaa", "bba"));    
  console.log("Result:", strStr("abc", ""));         

  